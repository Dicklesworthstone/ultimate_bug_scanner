"""ubs_core.py_scan — contract-v2 orchestrator for the Python module (bead 0xjg.5).

ONE ``python3 -m ubs_core.py_scan`` process replaces the legacy module's
~250-400 process spawns (57 rg pipelines, 37 python heredocs, ~156 ast-grep
invocations). Layers, in legacy-equivalent order:

1. ``ubs_core.py_patterns.*``  Pattern tables — faithful ports of the legacy
   rg pipelines (category-scoped regex + threshold-descending severity
   ladders; DISTINCT-LINE project-wide counting).
2. ``ubs_core.py_detectors.*`` Detector modules — ports of the legacy python
   heredoc detectors (AST walkers emitting per-detection records).
3. Registry analyzers (taint_py, lifecycle_py, guards_py, ctcompare_py) —
   already migrated in A2; ``python.narrowing.*`` (bead D4, no legacy
   counterpart) is disabled by default so v2 stays at legacy parity; opt in
   with ``--enable-new-analyzers``.
4. ``ubs_core.py_ast`` — the consolidated ast-grep rule pack (51 rules
   generated by ``ubs_core.py_rules``), one ``scan -c`` invocation per batch.

The NDJSON sink is the single source of truth: totals are recounted from it
(js parity), ``--json-out`` carries a run_lang-compatible summary object plus
the raw records and a legacy-shaped per-category report (issue-64 payload
with title/description/samples), and ``--text-out`` renders the legacy text
report. The bash caller appends record-less section headers and the final
"Summary Statistics:" block (see run_v2_legacy_parity_bridges_py).

Python 3.9+ stdlib only.
"""
